def t(key: str, locale: str = "ko", **kwargs) -> str:
    """Resolve a localized string with fallback to Korean and optional formatting."""
    table = STRINGS.get(locale) or STRINGS["ko"]
    text = table.get(key) or STRINGS["ko"].get(key) or key
    return text.format(**kwargs) if kwargs else text


def state_label(state: str | None, locale: str = "ko") -> str:
    """Translate an execution state constant to a user-facing label."""
    if not state:
        return "—"
    table = STATES_I18N.get(locale) or STATES_I18N["ko"]
    return table.get(state, state)
